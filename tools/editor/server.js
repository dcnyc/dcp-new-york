/* ============================================================================
   DCP New York — local visual editor
   ----------------------------------------------------------------------------
   Serves the real site from disk and injects an editing overlay into the
   response. The overlay is injected at SERVE TIME: no .html file on disk ever
   contains editor markup, and tools/ is excluded from the deploy allowlist, so
   none of this can reach the published site.

       node tools/editor/server.js          → http://127.0.0.1:8787

   Add ?preview=1 to any URL to see the page with no editor chrome at all.
   ========================================================================== */

