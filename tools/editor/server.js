/* ---------------------------------------------------------------- helpers */

const pad2 = n => String(n).padStart(2, '0');
const titleCase = s => s.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
const slugify = s => s.toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

function send(res, code, body, type) {
  res.writeHead(code, { 'Content-Type': type || 'text/plain; charset=utf-8' });
  res.end(body);
}
const sendJson = (res, code, obj) =>
  send(res, code, JSON.stringify(obj, null, 2), 'application/json');

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = []; let size = 0;
    req.on('data', c => {
      size += c.length;
      if (size > 60 * 1024 * 1024) { reject(new Error('upload too large (60MB limit)')); req.destroy(); return; }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks)));
    req.on('error', reject);
  });
}

function run(cmd, args) {
  return new Promise(resolve => {
    execFile(cmd, args, { cwd: ROOT, maxBuffer: 10 * 1024 * 1024 }, (err, stdout, stderr) =>
      resolve({ ok: !err, stdout: stdout || '', stderr: stderr || '' }));
  });
}
const git = args => run('git', args);

/* Width/height from the JPEG header, so no image library is needed. */
function jpegSize(buf) {
  if (buf.length < 4 || buf[0] !== 0xFF || buf[1] !== 0xD8) return null;
  let i = 2;
  while (i < buf.length - 9) {
    if (buf[i] !== 0xFF) { i++; continue; }
    const m = buf[i + 1];
    if (m >= 0xC0 && m <= 0xCF && m !== 0xC4 && m !== 0xC8 && m !== 0xCC) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    const len = buf.readUInt16BE(i + 2);
    if (len < 2) return null;
    i += 2 + len;
  }
  return null;
}

function readConfig() {
  try { return JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8')); }
  catch (_) { return { galleries: {} }; }
}
const writeConfig = cfg => fs.writeFileSync(CONFIG_FILE, JSON.stringify(cfg, null, 2) + '\n', 'utf8');

/* ------------------------------------------------------- page discovery */

/* Every page is found on disk, so a page added through the editor shows up
   without anything being registered by hand. */
function discoverPages() {
  const found = [];

  if (fs.existsSync(path.join(ROOT, 'index.html'))) {
    found.push({ slug: '', path: 'index.html', url: '/' });
  }
  for (const d of fs.readdirSync(ROOT, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name.startsWith('.') || NOT_PAGES.has(d.name)) continue;
    if (!fs.existsSync(path.join(ROOT, d.name, 'index.html'))) continue;
    found.push({ slug: d.name, path: `${d.name}/index.html`, url: `/${d.name}/` });
  }

  const cfg = readConfig();
  return found.map(p => {
    const html = fs.readFileSync(path.join(ROOT, p.path), 'utf8');
    const imgDir = p.slug ? `assets/img/${p.slug}` : 'assets/img/portraits';
    const hasImages = fs.existsSync(path.join(ROOT, imgDir));

    let type = null;
    if (html.includes('headshot-grid')) type = 'grid';
    else if (html.includes('carousel__track')) type = 'carousel';

    return Object.assign({}, p, {
      label: (cfg.pages && cfg.pages[p.path] && cfg.pages[p.path].label)
             || LABELS[p.path] || titleCase(p.slug),
      gallery: (type && hasImages) ? (p.slug || 'portraits') : null,
      dir: imgDir,
      type,
      builtByScript: BUILT_BY_SCRIPT.has(p.path),
    });
  });
}

const pageByGallery = name => discoverPages().find(p => p.gallery === name);
const pageByPath = rel => discoverPages().find(p => p.path === rel);

function listGallery(name) {
  const p = pageByGallery(name);
  if (!p) return [];
  try {
    return fs.readdirSync(path.join(ROOT, p.dir)).filter(f => /\.jpe?g$/i.test(f)).sort();
  } catch (_) { return []; }
}

function gallerySettings(name) {
  const p = pageByGallery(name);
  const defaults = p && p.type === 'grid' ? { columns: 3 } : { showControls: true };
  return Object.assign(defaults, (readConfig().galleries || {})[name] || {});
}

function publishedSet() {
  try {
    const wf = fs.readFileSync(path.join(ROOT, '.github/workflows/pages.yml'), 'utf8');
    const block = wf.match(/PUBLISH=\(([\s\S]*?)\)/);
    if (!block) return null;
    return new Set(block[1].split('\n').map(s => s.trim()).filter(Boolean));
  } catch (_) { return null; }
}

const NAV = require(path.join(ROOT, 'tools', 'nav.js'));

const navOrder = () => NAV.navItems().map(i => i.path);
const menuSet = () => new Set(navOrder());

/* Rewrites the four menus inside a hand-written page. The generated pages get
   theirs from tools/build.sh, which calls the same module. */
function applyNavToPage(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) return;

  const slug = rel === 'index.html' ? '' : rel.split('/')[0];
  const prefix = slug ? '../' : '';
  const home = slug ? '../' : './';
  let html = fs.readFileSync(abs, 'utf8');

  html = html.replace(
    /(<div class="nav-side nav-side--left">[\s\S]*?<\/button>\n)[\s\S]*?(\n[ \t]*<\/div>)/,
    (_m, head, tail) => head + NAV.emit('header-left', prefix, home, rel) + tail);

  html = html.replace(
    /(<div class="nav-side nav-side--right">\n)[\s\S]*?(\n[ \t]*<\/div>)/,
    (_m, head, tail) => head + NAV.emit('header-right', prefix, home, rel) + tail);

  html = html.replace(
    /(<button class="overlay-close[^>]*><\/button>\n)[\s\S]*?(\n[ \t]*<\/div>)/,
    (_m, head, tail) => head + NAV.emit('overlay', prefix, home, rel) + tail);

  html = html.replace(
    /(<nav class="footer__menu"[^>]*>\n)[\s\S]*?(\n[ \t]*<\/nav>)/,
    (_m, head, tail) => head + NAV.emit('footer', prefix, home, rel) + tail);

  fs.writeFileSync(abs, html, 'utf8');
}

/* Push the current menu into every page: build.sh for the generated ones,
   a direct rewrite for the rest. */
async function applyNavEverywhere() {
  const built = await run('bash', ['tools/build.sh']);
  discoverPages()
    .filter(p => !p.builtByScript)
    .forEach(p => applyNavToPage(p.path));
  return built;
}

/* ---------------------------------------------------- markup regeneration */

function slidesMarkup(page, files) {
  const prefix = page.slug ? '../' : '';
  return files.map(f => {
    const d = jpegSize(fs.readFileSync(path.join(ROOT, page.dir, f))) || { width: 1200, height: 800 };
    const alt = f.replace(/^\d+-/, '').replace(/\.jpe?g$/i, '').replace(/[-_]+/g, ' ');
    return `          <div class="carousel__slide"><img src="${prefix}${page.dir}/${f}" alt="${alt}" width="${d.width}" height="${d.height}" loading="lazy" draggable="false"></div>`;
  }).join('\n');
}

function gridMarkup(page, files) {
  const cols = gallerySettings(page.gallery).columns;
  const prefix = page.slug ? '../' : '';
  const rows = files.map((f, i) => {
    const d = jpegSize(fs.readFileSync(path.join(ROOT, page.dir, f))) || { width: 1600, height: 1600 };
    return `      <button class="headshot-cell js-lb-open" type="button" aria-label="View photo ${i + 1} of ${files.length} full size">\n` +
           `        <img src="${prefix}${page.dir}/${f}" alt="Professional headshot by DCP New York" width="${d.width}" height="${d.height}" loading="lazy">\n` +
           `      </button>`;
  });
  return `    <section class="headshot-grid" data-cols="${cols}">\n${rows.join('\n')}\n    </section>`;
}

async function regenerate(galleryName) {
  const page = pageByGallery(galleryName);
  if (!page) throw new Error('unknown gallery');

  if (page.builtByScript) return run('bash', ['tools/build.sh']);

  const file = path.join(ROOT, page.path);
  let html = fs.readFileSync(file, 'utf8');
  const files = listGallery(galleryName);

  if (page.type === 'grid') {
    const re = /[ \t]*<section class="headshot-grid"[^>]*>[\s\S]*?<\/section>/;
    if (!re.test(html)) throw new Error('photo grid not found in ' + page.path);
    html = html.replace(re, gridMarkup(page, files));
  } else {
    const re = /(<div class="carousel__track">)([\s\S]*?)(\n[ \t]*<\/div>)/;
    if (!re.test(html)) throw new Error('carousel not found in ' + page.path);
    html = html.replace(re, (_m, open, _mid, close) =>
      open + (files.length ? '\n' + slidesMarkup(page, files) : '') + close);
  }

  fs.writeFileSync(file, html, 'utf8');
  return { ok: true, stdout: 'regenerated ' + page.path };
}

function applyOrder(galleryName, order) {
  const page = pageByGallery(galleryName);
  const dir = path.join(ROOT, page.dir);
  const existing = listGallery(galleryName);

  if (order.length !== existing.length || !order.every(f => existing.includes(f))) {
    throw new Error(
      'This page is out of step with the photo folder, so the order was not saved. ' +
      'Reload the page and try again.'
    );
  }

  const targets = order.map((file, i) => {
    const n = pad2(i + 1);
    const stem = page.type === 'grid' ? null : file.replace(/^\d+-/, '');
    return { from: file, to: stem ? `${n}-${stem}` : `headshot-${n}.jpg` };
  });

  const stamp = Date.now();
  targets.forEach((t, i) => fs.renameSync(path.join(dir, t.from), path.join(dir, `.tmp-${stamp}-${i}`)));
  targets.forEach((t, i) => fs.renameSync(path.join(dir, `.tmp-${stamp}-${i}`), path.join(dir, t.to)));
  return targets;
}

