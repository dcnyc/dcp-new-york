/* ------------------------------------------------- editable text scanning */

function scanEditable(html) {
  const mainStart = html.indexOf('<main');
  const mainEnd = html.indexOf('</main>');
  if (mainStart === -1 || mainEnd === -1) return [];
  const slice = html.slice(mainStart, mainEnd);
  const re = /<(h1|h2|h3|h4|h5|h6|p)(\s[^>]*)?>([\s\S]*?)<\/\1>/g;
  const out = [];
  let m;
  while ((m = re.exec(slice))) {
    const innerStart = mainStart + m.index + m[0].indexOf('>', m[0].indexOf('<' + m[1])) + 1;
    out.push({ tag: m[1], start: innerStart, end: innerStart + m[3].length });
  }
  return out;
}

const hashOf = s => {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h * 33) ^ s.charCodeAt(i)) >>> 0;
  return String(h);
};
const escapeHtml = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* ---------------------------------------------------------------- serving */

const editableMaps = new Map();

function injectEditor(html, pagePath) {
  const ranges = scanEditable(html);
  editableMaps.set(pagePath, { hash: hashOf(html), ranges });

  let out = '', cursor = 0;
  ranges.forEach((r, i) => {
    const openStart = html.lastIndexOf('<', r.start - 1);
    out += html.slice(cursor, openStart);
    out += html.slice(openStart, r.start).replace(/>$/, ` data-ed="${i}">`);
    cursor = r.start;
  });
  out += html.slice(cursor);

  const page = pageByPath(pagePath);
  const boot = `
<link rel="stylesheet" href="/__editor/editor.css">
<script>window.__EDITOR__=${JSON.stringify({ page: pagePath, gallery: page ? page.gallery : null })};</script>
<script src="/__editor/editor.js"></script>
`;
  return out.includes('</body>') ? out.replace('</body>', boot + '</body>') : out + boot;
}

/* -------------------------------------------------------------------- API */

async function handleApi(req, res, url, query) {
  const route = url.replace('/__editor/api/', '');

  if (route === 'status') {
    const [status, branch, ahead] = await Promise.all([
      git(['status', '--porcelain']),
      git(['rev-parse', '--abbrev-ref', 'HEAD']),
      git(['rev-list', '--count', '@{u}..HEAD']),
    ]);
    const changed = status.stdout.split('\n').map(s => s.trim()).filter(Boolean);
    return sendJson(res, 200, {
      branch: branch.stdout.trim(),
      changed, changedCount: changed.length,
      unpushed: Number((ahead.stdout || '0').trim()) || 0,
    });
  }

  if (route === 'pages') {
    const published = publishedSet();
    const order = navOrder();
    const inMenu = new Set(order);

    /* Menu pages come back in menu order, not alphabetically, so the list
       mirrors what a visitor sees. The rest follow, alphabetically. */
    const all = discoverPages().map(p => ({
      path: p.path, url: p.url, label: p.label, gallery: p.gallery, type: p.type,
      photos: p.gallery ? listGallery(p.gallery).length : 0,
      inMenu: inMenu.has(p.path),
      published: published ? published.has(p.slug || 'index.html') : true,
    }));

    const menu = order.map(pp => all.find(p => p.path === pp)).filter(Boolean);
    const rest = all.filter(p => !inMenu.has(p.path))
                    .sort((a, b) => a.label.localeCompare(b.label));

    return sendJson(res, 200, { pages: menu.concat(rest), nav: order });
  }

  if (route === 'settings' && req.method === 'GET') {
    const gallery = query.get('gallery');
    const page = pageByGallery(gallery);
    if (!page) return sendJson(res, 400, { error: 'unknown gallery' });
    return sendJson(res, 200, {
      gallery, type: page.type, settings: gallerySettings(gallery), photos: listGallery(gallery),
    });
  }

  if (req.method !== 'POST') return sendJson(res, 405, { error: 'POST required' });

  /* Upload writes the file and returns immediately. Resizing and rebuilding
     happen once in `finalize`, so dropping twelve photos spawns PowerShell
     once rather than twelve times. */
  if (route === 'gallery/upload') {
    const gallery = req.headers['x-gallery'];
    const rawName = String(req.headers['x-filename'] || 'photo.jpg');
    const page = pageByGallery(gallery);
    if (!page) return sendJson(res, 400, { error: 'unknown gallery' });

    const buf = await readBody(req);
    if (!jpegSize(buf)) return sendJson(res, 400, { error: `${rawName} is not a JPEG` });

    const next = listGallery(gallery).length + 1;
    const stem = rawName.replace(/\.[^.]+$/, '').replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'photo';
    const name = page.type === 'grid' ? `headshot-${pad2(next)}.jpg` : `${pad2(next)}-${stem}.jpg`;

    fs.writeFileSync(path.join(ROOT, page.dir, name), buf);
    return sendJson(res, 200, { added: name });
  }

  if (route === 'gallery/finalize') {
    const { gallery } = JSON.parse((await readBody(req)).toString('utf8') || '{}');
    const page = pageByGallery(gallery);
    if (!page) return sendJson(res, 400, { error: 'unknown gallery' });

    const resize = await run('powershell', [
      '-NoProfile', '-ExecutionPolicy', 'Bypass',
      '-File', path.join('tools', 'resize-images.ps1'), '-Folder', page.dir,
    ]);
    const rebuild = await regenerate(gallery);
    return sendJson(res, 200, { ok: true, resize: resize.stdout.trim(), rebuild: rebuild.ok });
  }

  const body = JSON.parse((await readBody(req)).toString('utf8') || '{}');

  /* ---- reorder the site menu ---- */
  if (route === 'nav') {
    const order = Array.isArray(body.order) ? body.order : null;
    if (!order) return sendJson(res, 400, { error: 'an order is required' });

    const known = new Set(discoverPages().map(p => p.path));
    const bad = order.filter(p => !known.has(p));
    if (bad.length) return sendJson(res, 400, { error: 'unknown page: ' + bad[0] });

    /* A page that is not deployed must not be linked, or the live site gets a
       menu item that 404s for every visitor. */
    const published = publishedSet();
    if (published) {
      const draft = order.find(p => {
        const page = discoverPages().find(x => x.path === p);
        return page && !published.has(page.slug || 'index.html');
      });
      if (draft) {
        const label = discoverPages().find(x => x.path === draft).label;
        return sendJson(res, 400, {
          error: `"${label}" is a draft and is not on the live site, so it cannot go in the menu yet. ` +
                 `Add it to the PUBLISH list in .github/workflows/pages.yml first.`,
        });
      }
    }
    if (!order.includes('index.html')) {
      return sendJson(res, 400, { error: 'the home page has to stay in the menu' });
    }

    const cfg = readConfig();
    cfg.nav = order;
    writeConfig(cfg);

    const built = await applyNavEverywhere();
    return sendJson(res, 200, { ok: true, nav: order, rebuild: built.ok });
  }

  if (route === 'pages/create') {
    const label = String(body.label || '').trim();
    if (!label) return sendJson(res, 400, { error: 'a page name is required' });
    const slug = slugify(label);
    if (!slug) return sendJson(res, 400, { error: 'that name has no usable letters or numbers' });
    if (NOT_PAGES.has(slug)) return sendJson(res, 400, { error: `"${slug}" is a reserved folder name` });
    if (fs.existsSync(path.join(ROOT, slug))) return sendJson(res, 400, { error: `a page or folder called "${slug}" already exists` });

    fs.mkdirSync(path.join(ROOT, slug), { recursive: true });
    fs.mkdirSync(path.join(ROOT, 'assets/img', slug), { recursive: true });
    fs.writeFileSync(path.join(ROOT, slug, 'index.html'), newPageHtml(slug, label), 'utf8');
    fs.writeFileSync(path.join(ROOT, 'assets/img', slug, '.gitkeep'),
      `Photos for the "${label}" page. Named NN-name.jpg; the number sets the order.\n`);

    /* Hold the photos back. A draft page is not deployed, but everything
       under assets/ is published wholesale, so without this its photos would
       be reachable at their direct URLs the moment they were committed. The
       rule is removed when the page is launched. */
    const ignorePath = path.join(ROOT, '.gitignore');
    const rule = `/assets/img/${slug}/*.jpg`;
    let ignore = fs.existsSync(ignorePath) ? fs.readFileSync(ignorePath, 'utf8') : '';
    if (!ignore.includes(rule)) {
      ignore = ignore.replace(/\s*$/, '\n') +
        `\n# Photos for the draft "${label}" page. Delete this line when it launches.\n${rule}\n`;
      fs.writeFileSync(ignorePath, ignore, 'utf8');
    }

    const cfg = readConfig();
    cfg.pages = cfg.pages || {};
    cfg.pages[`${slug}/index.html`] = { label };
    writeConfig(cfg);

    return sendJson(res, 200, { ok: true, slug, url: `/${slug}/`, label, photosHeldBack: true });
  }

  if (route === 'gallery/reorder') {
    const { gallery, order } = body;
    if (!pageByGallery(gallery)) return sendJson(res, 400, { error: 'unknown gallery' });
    try {
      const moved = applyOrder(gallery, order);
      const rebuild = await regenerate(gallery);
      /* Hand back the new names. Reordering renames every file, so without
         this the page would keep sending the old ones and the next drag
         would be rejected. */
      return sendJson(res, 200, {
        ok: true, moved: moved.length, rebuild: rebuild.ok, files: listGallery(gallery),
      });
    } catch (e) { return sendJson(res, 400, { error: e.message }); }
  }

  if (route === 'gallery/delete') {
    const { gallery, file } = body;
    const page = pageByGallery(gallery);
    if (!page) return sendJson(res, 400, { error: 'unknown gallery' });
    const target = path.join(ROOT, page.dir, path.basename(file));
    if (!fs.existsSync(target)) return sendJson(res, 404, { error: 'file not found' });

    const bin = path.join(ROOT, '.originals', 'removed');
    fs.mkdirSync(bin, { recursive: true });
    fs.copyFileSync(target, path.join(bin, `${Date.now()}-${path.basename(file)}`));
    fs.unlinkSync(target);

    applyOrder(gallery, listGallery(gallery));
    const rebuild = await regenerate(gallery);
    return sendJson(res, 200, { ok: true, remaining: listGallery(gallery).length, rebuild: rebuild.ok });
  }

  if (route === 'settings') {
    const { gallery, settings } = body;
    if (!pageByGallery(gallery)) return sendJson(res, 400, { error: 'unknown gallery' });
    const cfg = readConfig();
    cfg.galleries = cfg.galleries || {};
    cfg.galleries[gallery] = Object.assign(gallerySettings(gallery), settings || {});
    writeConfig(cfg);
    const rebuild = await regenerate(gallery);
    return sendJson(res, 200, { ok: true, settings: cfg.galleries[gallery], rebuild: rebuild.ok });
  }

  if (route === 'text') {
    const { page, index, text } = body;
    const abs = path.join(ROOT, page);
    if (!abs.startsWith(ROOT) || !fs.existsSync(abs)) return sendJson(res, 400, { error: 'unknown page' });
    const html = fs.readFileSync(abs, 'utf8');
    const map = editableMaps.get(page);
    if (!map || map.hash !== hashOf(html)) {
      return sendJson(res, 409, { error: 'the page changed on disk since it was loaded — reload and try again' });
    }
    const r = map.ranges[index];
    if (!r) return sendJson(res, 400, { error: 'unknown text block' });
    fs.writeFileSync(abs, html.slice(0, r.start) + escapeHtml(text) + html.slice(r.end), 'utf8');
    editableMaps.delete(page);
    return sendJson(res, 200, { ok: true });
  }

  if (route === 'publish') {
    const message = (body.message || '').trim() || 'Update site content';
    const log = [];
    const add = await git(['add', '-A']);
    log.push('$ git add -A', add.stdout + add.stderr);

    const staged = await git(['diff', '--cached', '--name-only']);
    if (!staged.stdout.trim()) {
      const push = await git(['push']);
      log.push('$ git push', push.stdout + push.stderr);
      return sendJson(res, 200, { ok: push.ok, nothingToCommit: true, log: log.join('\n') });
    }
    const commit = await git(['commit', '-m', message]);
    log.push('$ git commit', commit.stdout + commit.stderr);
    if (!commit.ok) return sendJson(res, 500, { ok: false, log: log.join('\n') });
    const push = await git(['push']);
    log.push('$ git push', push.stdout + push.stderr);
    return sendJson(res, push.ok ? 200 : 500, { ok: push.ok, log: log.join('\n') });
  }

  return sendJson(res, 404, { error: 'unknown endpoint' });
}

/* ------------------------------------------------------------------ server */

http.createServer(async (req, res) => {
  try {
    const [rawPath, rawQuery] = req.url.split('?');
    const query = new URLSearchParams(rawQuery || '');

    if (rawPath.startsWith('/__editor/api/')) return await handleApi(req, res, rawPath, query);

    if (rawPath === '/__editor/editor.css' || rawPath === '/__editor/editor.js') {
      const file = path.join(__dirname, path.basename(rawPath));
      return send(res, 200, fs.readFileSync(file), TYPES[path.extname(file)]);
    }

    let rel = decodeURIComponent(rawPath).replace(/^\/+/, '');
    if (rel === '' || rel.endsWith('/')) rel += 'index.html';
    let abs = path.join(ROOT, rel);
    if (!abs.startsWith(ROOT)) return send(res, 403, 'forbidden');
    if (fs.existsSync(abs) && fs.statSync(abs).isDirectory()) abs = path.join(abs, 'index.html');
    if (!fs.existsSync(abs)) return send(res, 404, 'Not found: ' + rel);

    if (path.extname(abs) === '.html') {
      const pageRel = path.relative(ROOT, abs).replace(/\\/g, '/');
      const html = fs.readFileSync(abs, 'utf8');
      /* ?preview=1 serves the page exactly as it will be published. */
      const out = query.get('preview') ? html : injectEditor(html, pageRel);
      return send(res, 200, out, TYPES['.html']);
    }

    res.writeHead(200, {
      'Content-Type': TYPES[path.extname(abs)] || 'application/octet-stream',
      'Cache-Control': 'no-store',
    });
    fs.createReadStream(abs).pipe(res);
  } catch (e) {
    send(res, 500, 'Editor error: ' + e.message);
  }
}).listen(PORT, '127.0.0.1', () => {
  console.log('\n  DCP New York — visual editor');
  console.log('  ---------------------------------------------');
  console.log('  http://127.0.0.1:' + PORT);
  console.log('\n  Editing writes to the real files in this repo.');
  console.log('  Publish runs git add / commit / push.');
  console.log('  Stop with Ctrl+C.\n');
});
